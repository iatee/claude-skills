#!/usr/bin/env node
// Generates the skill catalog from catalog.json, each SKILL.md and manifest.json.
//
//   node scripts/catalog.mjs          Write the catalog into README.md and docs/guides/catalog.md.
//   node scripts/catalog.mjs --check  Fail if either file is out of date (CI runs this).

import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
import { loadCatalog } from "./catalog-data.mjs";

const { rows, errors } = loadCatalog(ROOT);

const cell = (s) => s.replace(/\|/g, "\\|");
// Each skill name links to its own page: absolute in the README, site-relative in the catalog guide.
const table = (base) =>
  [
    "| Skill | Plugin | What it does | Use it when | How to start it | Credit |",
    "|---|---|---|---|---|---|",
    ...rows.map((r) => `| [**${r.name}**](${base}/skills/${r.name}/) | \`${r.plugin}\` | ${cell(r.what)} | ${cell(r.when)} | ${r.trigger} | ${r.credit} |`),
  ].join("\n");

const NOT_INCLUDED = `**Not included, and why**

- \`ask-matt\`: a hand-written guide to Matt Pocock's skills. The suggester does the same job for every installed skill.
- \`mem-search\`, \`mem-setup\`: part of the [claude-mem](https://github.com/thedotmack/claude-mem) plugin and useless without it. Install that plugin instead.
- \`prompt-cache-control\`: a plugin, not a skill. See [claude-code-templates](https://github.com/davila7/claude-code-templates).
- \`web-design-guidelines\` (Vercel): no license, and \`impeccable\` covers it.
- \`apple-design-skills\`: \`impeccable\` already ships Apple and Android guideline references.`;

const block = (base) => `${table(base)}\n\n${NOT_INCLUDED}`;
const outputs = {
  "README.md": (text) =>
    text.replace(
      /<!-- catalog:start -->[\s\S]*?<!-- catalog:end -->/,
      () => `<!-- catalog:start -->\n${block("https://skills.garciabaertsch.com")}\n<!-- catalog:end -->`,
    ),
  "docs/guides/catalog.md": () =>
    `---
title: Skill catalog
description: Every skill in this collection, what it does, and when to use it.
editUrl: false
tableOfContents: false
---

<!-- Generated by scripts/catalog.mjs from catalog.json. Do not edit by hand. -->

${rows.length} skills and skill packs across ${new Set(rows.map((r) => r.plugin)).size} plugins. **How to start it** shows whether Claude can pick a skill up on its own ("Automatic") or whether you type the command yourself.

${block("")}
`,
};

const check = process.argv.includes("--check");
for (const [file, render] of Object.entries(outputs)) {
  const full = path.join(ROOT, file);
  const before = fs.existsSync(full) ? fs.readFileSync(full, "utf8") : "";
  const after = render(before);
  if (file === "README.md" && !before.includes("<!-- catalog:start -->")) errors.push("README.md is missing the catalog markers");
  if (before === after) continue;
  if (check) errors.push(`${file} is out of date: run node scripts/catalog.mjs`);
  else {
    fs.mkdirSync(path.dirname(full), { recursive: true });
    fs.writeFileSync(full, after);
    console.log(`wrote ${file}`);
  }
}

if (errors.length) {
  console.error(errors.map((e) => `✗ ${e}`).join("\n"));
  process.exit(1);
}
